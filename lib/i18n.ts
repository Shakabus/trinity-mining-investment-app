export type LanguageCode = 'en' | 'es' | 'ja' | 'de' | 'zh' | 'hi' | 'pt'

export const SUPPORTED_LANGUAGES: LanguageCode[] = ['en', 'es', 'ja', 'de', 'zh', 'hi', 'pt']

export const LANGUAGE_LABELS: Record<LanguageCode, string> = {
  en: 'English',
  es: 'Español',
  ja: '日本語',
  de: 'Deutsch',
  zh: '中文',
  hi: 'हिन्दी',
  pt: 'Português (BR)',
}

export function isSupportedLanguage(value: string): value is LanguageCode {
  return SUPPORTED_LANGUAGES.includes(value as LanguageCode)
}

export function languageFromCurrency(currency: string): LanguageCode {
  const code = currency.toUpperCase()
  if (code === 'EUR') return 'es'
  if (code === 'JPY') return 'ja'
  if (code === 'CHF') return 'de'
  if (code === 'CNY') return 'zh'
  if (code === 'INR') return 'hi'
  if (code === 'BRL') return 'pt'
  return 'en'
}

